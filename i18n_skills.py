def exact(lang):
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "characters.md")
    if lang not in ("en", "ja"):
        return {}
    k = 0 if lang == "en" else 1
    out = {}
    cur = None
    idx = 0
    for l in open(path, encoding="utf-8").read().splitlines():
        if l.startswith("### "):
            cur = l[4:].strip(); idx = 0; continue
        if cur is None or l.startswith("#") or l.startswith(">") or l.startswith("圖片") or not l.strip():
            continue
        tr = T.get(cur)
        if not tr:
            continue
        if l.startswith("(") and cur == "司馬炎":
            out[l.strip()] = tr[0][k]; continue
        m = re.match(r"^(\d+)\.\s*(.*)$", l)
        off = 1 if cur == "司馬炎" else 0
        if m and idx + off < len(tr):
            out[l.strip()] = f"{m.group(1)}. " + tr[idx + off][k]
            idx += 1
    return out
